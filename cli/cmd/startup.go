// Startup levels (N13, DC14). A command declares the startup it needs with
// the annotation initLevelKey, inherited from its parents; without one it
// gets the full startup.
//
//   - none: logging only (version, help, completion, runner install, beads,
//     mcp serve workflow).
//   - light: configuration read (never saved), secrets on demand, database
//     only when initDBKey is set (daemon, runner); no migration of the
//     keychain, workflows or deployments, no translation of the help.
//   - degraded: every step guarded, failures kept in startupReport, partial
//     App (doctor, repair, purge, config path, export).
//   - full: everything; a failure points to oh doctor / oh repair.
type initLevel string

const (
	levelNone     initLevel = "none"
	levelLight    initLevel = "light"
	levelDegraded initLevel = "degraded"
	levelFull     initLevel = "full"

	initLevelKey = "oh.init"
	initDBKey    = "oh.init.db"
)

// withInitLevel annotates cmd with its startup level.
func withInitLevel(cmd *cobra.Command, level initLevel) *cobra.Command {
	if cmd.Annotations == nil {
		cmd.Annotations = map[string]string{}
	}
	cmd.Annotations[initLevelKey] = string(level)
	return cmd
}

// withInitDB marks a light command that needs the database.
func withInitDB(cmd *cobra.Command) *cobra.Command {
	withInitLevel(cmd, levelLight)
	cmd.Annotations[initDBKey] = "1"
	return cmd
}

// initLevelOf is the startup level of cmd: its annotation or the closest
// parent's. Commands generated by cobra (help, completion) need none; the
// MCP server `workflow` only talks to the daemon socket.
func initLevelOf(cmd *cobra.Command, args []string) initLevel {
	if cmd.Name() == "help" || cmd.Name() == "completion" || cmd.Name() == cobra.ShellCompRequestCmd || cmd.Name() == cobra.ShellCompNoDescRequestCmd {
		return levelNone
	}
	if isMCPServe(cmd) && len(args) > 0 && args[0] == sessionspec.WorkflowMCPServer {
		return levelNone
	}
	for c := cmd; c != nil; c = c.Parent() {
		if l, ok := c.Annotations[initLevelKey]; ok {
			return initLevel(l)
		}
	}
	return levelFull
}

func needsDB(cmd *cobra.Command) bool {
	for c := cmd; c != nil; c = c.Parent() {
		if c.Annotations[initDBKey] == "1" {
			return true
		}
		if _, ok := c.Annotations[initLevelKey]; ok {
			return false
		}
	}
	return false
}

func isMCPServe(cmd *cobra.Command) bool {
	return cmd.Name() == "serve" && cmd.Parent() != nil && cmd.Parent().Name() == "mcp"
}

// StartupReport holds what failed during a degraded startup.
type StartupReport struct {
	Level            initLevel
	ConfigErr        error
	DBErr            error  // opening the database or reading its schema
	LastMigrationErr string // last failed migration (full startup)
	// SchemaVersion is the highest applied migration (-1: unknown),
	// BinaryMaxVersion the highest known by this oh, Pending the versions
	// still to apply, Newer the applied versions unknown to this oh.
	SchemaVersion    int
	BinaryMaxVersion int
	Pending          []int
	Newer            []int
}

// startupReport is the report of the current process (nil before startup).
var startupReport *StartupReport

// startupFor runs the startup of cmd's level.
func startupFor(cmd *cobra.Command, args []string) error {
	level := initLevelOf(cmd, args)
	switch level {
	case levelNone:
		// Messages of the MCP server follow the hub language.
		ensureLocale()
		return nil
	case levelLight:
		return initLight(needsDB(cmd))
	case levelDegraded:
		initDegraded()
		return nil
	}
	if cmd.Name() != "init" && cmd.Name() != "purge" {
		extractHubContent()
	}
	if err := initApp(); err != nil {
		return startupFailed(err)
	}
	// Former workflow configurations → team-state (v5 phase 2, v38).
	if cmd.Name() != "init" && cmd.Name() != "purge" {
		migrateLegacyWorkflowsAtStartup(cmd.Context(), os.Stderr)
	}
	// Former deployments: offered once (the TUI shows its own screen).
	if offerCleanupFor(cmd) {
		offerDeployCleanupAtStartup(cmd.Context(), os.Stderr, cmd.Name())
	}
	return nil
}

// extractHubContent extracts the embedded agents, skills and permissions
// when the binary changed.
func extractHubContent() {
	if hubcontent.NeedsExtract() {
		if err := hubcontent.Extract(hubcontent.HubContentDir()); err != nil {
			slog.Warn("failed to extract hub content", "error", err)
		}
	}
}

// startupError is a failed full startup: the message points to the
// commands that still work.
type startupError struct{ err error }

func (e *startupError) Error() string { return e.err.Error() }
func (e *startupError) Unwrap() error { return e.err }

func startupFailed(err error) error {
	var newer *sqlite.SchemaNewerError
	var mig *sqlite.MigrationError
	if errors.As(err, &newer) || errors.As(err, &mig) {
		return err // their message already says what to do
	}
	return &startupError{err: err}
}

// initLight is the startup of the background processes (daemon, runner,
// MCP servers): nothing is written to the configuration and no migration of
// the keychain runs (it may ask for a passphrase without a terminal).
func initLight(withDB bool) error {
	a, err := app.New()
	if err != nil {
		return startupFailed(err)
	}
	a.WithSecretStore(newLazySecrets(resolveSecretStore))
	if withDB {
		extractHubContent()
		s, err := sqlite.OpenWith(sqlite.DBPath(), sqlite.OpenOptions{AllowNewer: true})
		if err != nil {
			return startupFailed(fmt.Errorf("opening database: %w", err))
		}
		if n := s.SchemaNewer(); n != nil {
			slog.Warn("database schema is newer than this oh", "unknown", n.Unknown, "known", n.Known)
		}
		store = s
		wireStores(a, s)
	}
	application = a
	return nil
}

// initDegraded builds what it can: the commands that diagnose and repair
// (doctor, repair) must run with a broken configuration or database.
func initDegraded() {
	r := &StartupReport{Level: levelDegraded, SchemaVersion: -1, BinaryMaxVersion: sqlite.MaxKnownVersion()}
	startupReport = r

	cfg, err := config.Load()
	if err != nil || cfg == nil {
		r.ConfigErr = err
		if r.ConfigErr == nil {
			r.ConfigErr = errors.New("no configuration")
		}
		cfg = &config.Config{Name: "OpenHub"}
		cfg.CLI.Language = "en"
	} else {
		i18n.SetLocale(cfg.CLI.Language)
	}
	a := &app.App{Config: cfg, IO: app.DefaultIOStreams()}
	a.WithSecretStore(newLazySecrets(resolveSecretStore))
	application = a

	path := sqlite.DBPath()
	if _, err := os.Stat(path); err != nil {
		if !os.IsNotExist(err) {
			r.DBErr = err
		}
		return // created by the next full startup
	}
	raw, err := sqlite.OpenRaw(path)
	if err != nil {
		r.DBErr = err
		return
	}
	store = raw
	readSchemaReport(raw, r)
	// Never migrated here (oh repair --migrate does it, with a backup): the
	// stores are wired when the schema is the one this oh expects (or newer).
	if r.DBErr == nil && len(r.Pending) == 0 {
		wireStores(a, raw)
	}
}

func readSchemaReport(s *sqlite.Store, r *StartupReport) {
	r.LastMigrationErr = sqlite.LastMigrationError(s.Path())
	v, err := s.SchemaVersion()
	if err != nil {
		r.DBErr = err
		return
	}
	r.SchemaVersion = v
	r.Pending, _ = s.PendingMigrations()
	r.Newer, _ = s.UnknownMigrations()
}

// wireStores connects the stores of the database to the application.
func wireStores(a *app.App, s *sqlite.Store) {
	a.WithProjectStore(sqlite.NewProjectStore(s))
	a.WithSessionStore(sqlite.NewSessionStore(s))
	a.WithAgentEventStore(sqlite.NewAgentEventStore(s))
	prefs := sqlite.NewPreferenceStore(s)
	a.WithPreferences(prefs, prefs)
	a.WithStats(sessionstats.New(a.Sessions, a.Projects))
	a.WithToolVersion(func() (string, error) {
		if err := requireV2(context.Background()); err != nil {
			return "", err
		}
		return v5Tool.Version, nil
	})
}

// lazySecrets resolves the secret store on first use: a background process
// that never reads a secret never probes the keychain.
type lazySecrets struct {
	once    sync.Once
	resolve func() domain.SecretStore
	s       domain.SecretStore
}

func newLazySecrets(resolve func() domain.SecretStore) *lazySecrets {
	return &lazySecrets{resolve: resolve}
}

var errNoSecretStore = errors.New("no secret store available")

func (l *lazySecrets) get() domain.SecretStore {
	l.once.Do(func() { l.s = l.resolve() })
	return l.s
}

func (l *lazySecrets) Get(ctx context.Context, key string) (string, error) {
	if s := l.get(); s != nil {
		return s.Get(ctx, key)
	}
	return "", nil
}

func (l *lazySecrets) Set(ctx context.Context, key, value string) error {
	if s := l.get(); s != nil {
		return s.Set(ctx, key, value)
	}
	return errNoSecretStore
}

func (l *lazySecrets) Delete(ctx context.Context, key string) error {
	if s := l.get(); s != nil {
		return s.Delete(ctx, key)
	}
	return nil
}

func (l *lazySecrets) List(ctx context.Context) ([]string, error) {
	if s := l.get(); s != nil {
		return s.List(ctx)
	}
	return nil, nil
}

// keychainMigratedMarker records that the legacy keychain keys were
// migrated: the migration costs 8 to 16 keychain calls, made once.
func keychainMigratedMarker() string {
	return filepath.Join(config.HubDir(), ".keychain-keys-migrated")
}

// migrateKeychainKeysOnce renames the legacy keychain entries the first
// time only (full startup).
func migrateKeychainKeysOnce(secrets config.SecretMigrator) int {
	if secrets == nil {
		return 0
	}
	marker := keychainMigratedMarker()
	if _, err := os.Stat(marker); err == nil {
		return 0
	}
	n := config.MigrateKeychainKeys(secrets)
	if err := os.MkdirAll(filepath.Dir(marker), 0o700); err == nil {
		_ = os.WriteFile(marker, []byte("1\n"), 0o600)
	}
	return n
}
