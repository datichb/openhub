// N13: the startup level of each command (annotations, inherited).
func TestInitLevels(t *testing.T) {
	cases := map[string]initLevel{
		"version":                levelNone,
		"beads list":             levelNone,
		"runner install":         levelNone,
		"mcp serve workflow":     levelNone,
		"mcp serve gitlab":       levelLight,
		"daemon run":             levelLight,
		"runner run":             levelLight,
		"doctor":                 levelDegraded,
		"repair":                 levelDegraded,
		"purge":                  levelDegraded,
		"config path":            levelDegraded,
		"export":                 levelDegraded,
		"project list":           levelFull,
		"run":                    levelFull,
		"config set":             levelFull,
		"daemon status":          levelFull,
		"session list":           levelFull,
		"workflow list":          levelFull,
		"mcp setup":              levelFull,
		"budget show":            levelFull,
		"worktree list":          levelFull,
		"team status":            levelFull,
		"bundle show":            levelFull,
		"import":                 levelFull,
		"init":                   levelFull,
		"secrets list":           levelFull,
		"provider setup":         levelFull,
		"session attach":         levelFull,
		"daemon stop":            levelFull,
		"workflow validate":      levelFull,
		"config model show":      levelFull,
		"skill check":            levelFull,
		"migrate deploy-cleanup": levelFull,
	}
	for line, want := range cases {
		args := strings.Fields(line)
		c, rest, err := rootCmd.Find(args)
		require.NoError(t, err, line)
		assert.Equal(t, want, initLevelOf(c, rest), line)
	}
	// Generated by cobra at Execute.
	for _, name := range []string{"help", "completion", cobra.ShellCompRequestCmd} {
		assert.Equal(t, levelNone, initLevelOf(&cobra.Command{Use: name}, nil), name)
	}
	db := func(line string) bool {
		c, _, err := rootCmd.Find(strings.Fields(line))
		require.NoError(t, err)
		return needsDB(c)
	}
	assert.True(t, db("daemon run"))
	assert.True(t, db("runner run"))
	assert.False(t, db("mcp serve gitlab"))
	assert.False(t, db("doctor"))
}

type countingSecrets struct {
	gets int
	m    map[string]string
}

func (c *countingSecrets) Get(_ context.Context, k string) (string, error) {
	c.gets++
	return c.m[k], nil
}
func (c *countingSecrets) Set(_ context.Context, k, v string) error { c.m[k] = v; return nil }
func (c *countingSecrets) Delete(_ context.Context, k string) error { delete(c.m, k); return nil }
func (c *countingSecrets) List(context.Context) ([]string, error)   { return nil, nil }

// N13: the legacy keychain keys are migrated once (marker), not on every
// start.
func TestMigrateKeychainKeysOnce(t *testing.T) {
	t.Setenv("OH_HOME", t.TempDir())
	s := &countingSecrets{m: map[string]string{"gitlab-token": "x"}}
	assert.Equal(t, 1, migrateKeychainKeysOnce(s))
	assert.Equal(t, "x", s.m["openhub.mcp.gitlab.token"])
	first := s.gets
	assert.Positive(t, first)
	assert.Zero(t, migrateKeychainKeysOnce(s))
	assert.Equal(t, first, s.gets, "no keychain call after the first migration")
	assert.Zero(t, migrateKeychainKeysOnce(nil))
}

// N13: the secret store of the light and degraded startups is resolved on
// first use only.
func TestLazySecrets(t *testing.T) {
	resolved := 0
	inner := &countingSecrets{m: map[string]string{"k": "v"}}
	l := newLazySecrets(func() domain.SecretStore { resolved++; return inner })
	assert.Zero(t, resolved)
	v, err := l.Get(context.Background(), "k")
	require.NoError(t, err)
	assert.Equal(t, "v", v)
	_, _ = l.List(context.Background())
	assert.Equal(t, 1, resolved)

	none := newLazySecrets(func() domain.SecretStore { return nil })
	v, err = none.Get(context.Background(), "k")
	assert.NoError(t, err)
	assert.Empty(t, v)
	assert.ErrorIs(t, none.Set(context.Background(), "k", "v"), errNoSecretStore)
}

// storesOf lists the database stores of the application by name.
func storesOf(a *app.App) map[string]any {
	return map[string]any{
		"Projects": a.Projects, "Sessions": a.Sessions, "AgentEvents": a.AgentEvents, "Preferences": a.Preferences,
		"WorkflowUsage": a.WorkflowUsage, "Decisions": a.Decisions, "Usage": a.Usage, "Servers": a.Servers,
		"Grants": a.Grants, "Remotes": a.Remotes, "Checkpoints": a.Checkpoints, "Reports": a.Reports,
		"WikiProposals": a.WikiProposals, "History": a.History, "Fanout": a.Fanout,
	}
}

// wireStores fills every store of the container; a degraded startup without
// database leaves them all nil.
func TestWireStoresFillsEveryStore(t *testing.T) {
	a := &app.App{}
	for name, s := range storesOf(a) {
		assert.Nil(t, s, "%s is nil before the stores are wired", name)
	}
	wireStores(a, sqlitetest.New(t))
	for name, s := range storesOf(a) {
		assert.NotNil(t, s, "%s is wired", name)
	}
	assert.NotNil(t, a.Stats, "the stats provider is wired")
}

// Degraded startup: the database may be missing or unreadable, the stores
// stay nil and the container is still usable by oh doctor and oh repair.
func TestInitDegradedLeavesStoresNil(t *testing.T) {
	cases := map[string]func(t *testing.T){
		"no database": func(*testing.T) {},
		"unreadable database": func(t *testing.T) {
			require.NoError(t, os.WriteFile(sqlite.DBPath(), []byte("not a sqlite database, long enough to be read as a header"), 0o600))
		},
	}
	for name, prepare := range cases {
		t.Run(name, func(t *testing.T) {
			t.Setenv("OH_HOME", t.TempDir())
			oldApp, oldStore, oldReport := application, store, startupReport
			t.Cleanup(func() { application, store, startupReport = oldApp, oldStore, oldReport })
			store = nil
			prepare(t)

			initDegraded()

			require.NotNil(t, application, "the container exists")
			assert.NotNil(t, application.Config, "with a configuration")
			assert.NotNil(t, application.IO, "with its streams")
			assert.NotNil(t, application.Secrets, "with the secret store")
			for name, s := range storesOf(application) {
				assert.Nil(t, s, "%s stays nil without a usable database", name)
			}
		})
	}
}
