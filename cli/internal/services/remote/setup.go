// CIFile is the pipeline file of the oh-runner project.
const CIFile = ".gitlab-ci.yml"

// Errors of the setup.
var (
	ErrNoToken              = errors.New("no GitLab API token for this target")
	ErrRunnerProjectMissing = errors.New("oh-runner project not found")
	ErrForeignPipeline      = errors.New("the oh-runner project has a pipeline file not generated by oh")
	ErrWeakSecret           = errors.New("secret too short or multi-line: GitLab cannot mask it (8 characters minimum, one line)")
)

// Service sets up and checks remote targets.
type Service struct {
	// Secrets is the machine secret store (API token, trigger token).
	Secrets domain.SecretStore
	// SaveTarget persists a target in hub.toml.
	SaveTarget func(config.RemoteTarget) error
	// NewClient builds the GitLab client (default gitlab.New).
	NewClient func(baseURL, token string) *gitlab.Client
	// OhVersion is the version of the running oh (buildinfo.Version).
	OhVersion string
	// ToolName and ToolVersion identify the tool of the machine adapter,
	// installed in the job image.
	ToolName    string
	ToolVersion string

	// Sending (lot 5.A).
	Sessions domain.SessionStore
	Remote   domain.RemoteStore
	Git      Git   // default GitCLI
	Beads    Beads // default BdCLI
	// Human names the person of the machine, actor of the replayed
	// Beads writes (default gateway.ResolveHuman).
	Human        func(ctx context.Context, dir string) string
	Now          func() time.Time
	NewSessionID func() string

	// Return (lot 5.C).
	SessionsDir string // ~/.oh/sessions: <id>/remote/ keeps the envelope and the artifacts
	BundlesDir  string // ~/.oh/bundles
	// Target returns the remote target named name (hub.toml).
	Target func(name string) (*config.RemoteTarget, bool)
	// Adopt imports the transcripts into a local server group at location
	// (runsvc.Service.AdoptSession).
	Adopt func(ctx context.Context, sessionID string, transcripts [][]byte, location string) error
	// Worktree returns a worktree of the project on branch (created when missing).
	Worktree func(projectDir, branch string) (string, error)
	// Notify tells the user that a remote session is ready (system notification).
	Notify func(title, body string)
	// Reports receives the reports of the job (workflow_report) at fetch
	// time (nil: not imported).
	Reports *report.Service
	// Verifications receives the verifications run by oh in the job
	// (summary.json, R3-remote) at fetch time (nil: not imported).
	Verifications func(ctx context.Context, sessionID string, list []remote.SummaryVerification) (int, error)
}

func (s *Service) client(t config.RemoteTarget, token string) *gitlab.Client {
	if s.NewClient != nil {
		return s.NewClient(t.URL, token)
	}
	return gitlab.New(t.URL, token)
}

// StepStatus is the outcome of a setup or check step.
type StepStatus string

// Step statuses.
const (
	StepOK      StepStatus = "ok"      // present and valid
	StepCreated StepStatus = "created" // created by this call
	StepUpdated StepStatus = "updated" // replaced by this call
	StepWarn    StepStatus = "warn"    // usable, but something to fix
	StepFailed  StepStatus = "failed"  // blocking
	StepSkipped StepStatus = "skipped" // not checked (an earlier step failed)
)

// Step identifiers (stable: i18n keys cmd.remote.step.<id>).
const (
	StepAccess    = "access"
	StepGroup     = "group"
	StepProject   = "project"
	StepFeatures  = "features"
	StepProtected = "protected"
	StepPipeline  = "pipeline"
	StepTrigger   = "trigger"
	StepVariable  = "variable"
	StepRunners   = "runners"
	StepBinary    = "binary"
	StepJournal   = "journal_key"
)

// Step is one line of a report. Args are the values of the message
// (usernames, paths, variable names…), never a secret.
type Step struct {
	ID     string
	Status StepStatus
	Args   []string
	Err    error
}

// Report is the result of Setup or Check.
type Report struct {
	Target config.RemoteTarget
	Steps  []Step
}

// OK reports whether no step failed.
func (r *Report) OK() bool {
	for _, s := range r.Steps {
		if s.Status == StepFailed {
			return false
		}
	}
	return true
}

func (r *Report) add(id string, st StepStatus, err error, args ...string) {
	r.Steps = append(r.Steps, Step{ID: id, Status: st, Args: args, Err: err})
}

// LLMSecret is the provider key of the jobs.
type LLMSecret struct {
	Provider string // oh provider name (bedrock, anthropic, openrouter)
	Region   string // Bedrock region
	Key      string // API key (Bedrock API key, Anthropic key…)
}

// ProjectToken is the access token of one target project.
type ProjectToken struct {
	Path  string // full path of the project (resolved to its ID)
	Token string
}

// SetupRequest describes a setup run. Empty secrets are left untouched.
type SetupRequest struct {
	Target config.RemoteTarget
	// Token is a new API token (stored under Target.TokenKeyOrDefault()).
	Token string
	// Create creates the oh-runner project when it is missing.
	Create bool
	// Force replaces a pipeline file not generated by oh.
	Force          bool
	LLM            *LLMSecret
	Projects       []ProjectToken
	TeamStateToken string
	// OhBinary is a Linux oh binary to upload (development builds).
	OhBinary string
}

func validSecret(v string) bool {
	return len(v) >= 8 && !strings.ContainsAny(v, "\n\r")
}

// Setup creates or validates the oh-runner project of a target, its pipeline,
// trigger and variables, and saves the target. It stops at the first blocking
// step; the report lists what was done.
func (s *Service) Setup(ctx context.Context, req SetupRequest) (*Report, error) {
	t := req.Target
	if err := t.Validate(); err != nil {
		return nil, err
	}
	if err := (ciconfig.Options{Tag: t.Tag, Builder: t.Builder, Arch: t.Arch, Timeout: t.Timeout}).Validate(); err != nil {
		return nil, err
	}
	for _, v := range []string{req.TeamStateToken} {
		if v != "" && !validSecret(v) {
			return nil, ErrWeakSecret
		}
	}
	if req.LLM != nil && !validSecret(req.LLM.Key) {
		return nil, ErrWeakSecret
	}
	for _, p := range req.Projects {
		if !validSecret(p.Token) {
			return nil, fmt.Errorf("%s: %w", p.Path, ErrWeakSecret)
		}
	}
	if s.Secrets == nil {
		return nil, errors.New("no secret store available")
	}
	if req.Token != "" {
		if err := s.Secrets.Set(ctx, t.TokenKeyOrDefault(), req.Token); err != nil {
			return nil, fmt.Errorf("storing the GitLab token: %w", err)
		}
	}
	token, _ := s.Secrets.Get(ctx, t.TokenKeyOrDefault())
	if token == "" {
		return nil, ErrNoToken
	}
	c := s.client(t, token)
	rep := &Report{Target: t}

	if _, err := s.access(ctx, c, rep); err != nil {
		return rep, err
	}
	g, err := c.Group(ctx, t.Group)
	if err != nil {
		rep.add(StepGroup, StepFailed, err, t.Group)
		return rep, err
	}
	rep.add(StepGroup, StepOK, nil, g.FullPath)

	path := t.RunnerProjectPath()
	p, err := c.Project(ctx, path)
	switch {
	case gitlab.IsNotFound(err) && req.Create:
		if !strings.HasPrefix(path, strings.Trim(t.Group, "/")+"/") || strings.Count(strings.TrimPrefix(path, strings.Trim(t.Group, "/")+"/"), "/") > 0 {
			err = fmt.Errorf("cannot create %s: it must be a direct child of the group %s", path, t.Group)
			rep.add(StepProject, StepFailed, err, path)
			return rep, err
		}
		name := path[strings.LastIndexByte(path, '/')+1:]
		p, err = c.CreateProject(ctx, gitlab.CreateProjectRequest{Name: name, Path: name, NamespaceID: g.ID,
			Description: "oh remote sessions (pipeline generated by oh remote setup)"})
		if err != nil {
			rep.add(StepProject, StepFailed, err, path)
			return rep, err
		}
		rep.add(StepProject, StepCreated, nil, p.PathWithNamespace)
	case gitlab.IsNotFound(err):
		rep.add(StepProject, StepFailed, ErrRunnerProjectMissing, path)
		return rep, ErrRunnerProjectMissing
	case err != nil:
		rep.add(StepProject, StepFailed, err, path)
		return rep, err
	default:
		rep.add(StepProject, StepOK, nil, p.PathWithNamespace)
	}
	t.RunnerProjectID = p.ID
	t.RunnerProject = p.PathWithNamespace
	rep.Target = t
	pid := fmt.Sprint(p.ID)

	if !s.features(rep, p) {
		return rep, errors.New("the oh-runner project lacks the package or container registry")
	}
	branch := p.DefaultBranch
	if branch == "" {
		branch = "main"
	}
	s.protected(ctx, c, rep, pid, branch)

	if err := s.pipeline(ctx, c, rep, pid, branch, t, req.Force); err != nil {
		return rep, err
	}
	if err := s.trigger(ctx, c, rep, pid, t); err != nil {
		return rep, err
	}
	if err := s.variables(ctx, c, rep, pid, req); err != nil {
		return rep, err
	}
	if err := s.journalKeyPair(ctx, c, rep, pid, branch); err != nil {
		return rep, err
	}
	s.runners(ctx, c, rep, pid, t)
	if req.OhBinary != "" {
		pkg, err := s.uploadBinary(ctx, c, pid, req.OhBinary, archOf(t))
		if err != nil {
			rep.add(StepBinary, StepFailed, err, s.OhVersion)
			return rep, err
		}
		if t.Binaries == nil {
			t.Binaries = map[string]string{}
		}
		t.Binaries[BinaryKey(s.OhVersion, archOf(t))] = pkg
		rep.Target = t
		rep.add(StepBinary, StepUpdated, nil, s.OhVersion, pkg[:12])
	} else {
		s.binary(rep, t)
	}

	if s.SaveTarget != nil {
		if err := s.SaveTarget(t); err != nil {
			return rep, fmt.Errorf("saving the remote target: %w", err)
		}
	}
	return rep, nil
}

// Check verifies a configured target without changing anything.
func (s *Service) Check(ctx context.Context, t config.RemoteTarget) *Report {
	rep := &Report{Target: t}
	token := ""
	if s.Secrets != nil {
		token, _ = s.Secrets.Get(ctx, t.TokenKeyOrDefault())
	}
	if token == "" {
		rep.add(StepAccess, StepFailed, ErrNoToken, t.TokenKeyOrDefault())
		return rep
	}
	c := s.client(t, token)
	if _, err := s.access(ctx, c, rep); err != nil {
		return rep
	}
	path := t.RunnerProjectPath()
	if t.RunnerProjectID != 0 {
		path = fmt.Sprint(t.RunnerProjectID)
	}
	p, err := c.Project(ctx, path)
	if err != nil {
		if gitlab.IsNotFound(err) {
			err = ErrRunnerProjectMissing
		}
		rep.add(StepProject, StepFailed, err, t.RunnerProjectPath())
		return rep
	}
	rep.add(StepProject, StepOK, nil, p.PathWithNamespace)
	pid := fmt.Sprint(p.ID)
	if !s.features(rep, p) {
		return rep
	}
	branch := p.DefaultBranch
	if branch == "" {
		branch = "main"
	}
	s.protected(ctx, c, rep, pid, branch)

	want, _ := ciconfig.Generate(ciOptions(t))
	cur, err := c.File(ctx, pid, CIFile, branch)
	switch {
	case gitlab.IsNotFound(err):
		rep.add(StepPipeline, StepFailed, errors.New("missing"), CIFile)
	case err != nil:
		rep.add(StepPipeline, StepFailed, err, CIFile)
	case bytes.Equal(cur, want):
		rep.add(StepPipeline, StepOK, nil, CIFile)
	case bytes.HasPrefix(cur, []byte(ciconfig.Marker)):
		rep.add(StepPipeline, StepWarn, errors.New("outdated: run oh remote setup"), CIFile)
	default:
		rep.add(StepPipeline, StepFailed, ErrForeignPipeline, CIFile)
	}

	trig, _ := s.Secrets.Get(ctx, t.TriggerKeyOrDefault())
	if trig == "" {
		rep.add(StepTrigger, StepFailed, errors.New("no trigger token on this machine"), t.TriggerKeyOrDefault())
	} else {
		rep.add(StepTrigger, StepOK, nil, t.TriggerKeyOrDefault())
	}
	s.reportVariables(ctx, c, rep, pid)
	if _, err := journalKeyState(ctx, c, pid, branch); err != nil {
		rep.add(StepJournal, StepFailed, err, remote.VarJournalKey)
	} else {
		rep.add(StepJournal, StepOK, nil, remote.VarJournalKey)
	}
	s.runners(ctx, c, rep, pid, t)
	s.binary(rep, t)
	return rep
}

// journalKeyDescription is the description of the journal private key
// variable: its public key, so that the pair can be checked without
// reading the secret.
func journalKeyDescription(pub string) string {
	return "oh: journal key of the remote sessions, public key " + pub
}

// ErrNoJournalKey is returned when oh-runner has no journal key pair (set
// up by an older oh, or incomplete): oh remote setup creates it.
var ErrNoJournalKey = errors.New("oh-runner has no journal key pair")

// journalKeyState returns the public key of the journal key pair of
// oh-runner: the file of the repository, matching the description of the
// private key variable (scoped to the run job).
func journalKeyState(ctx context.Context, c *gitlab.Client, pid, branch string) (string, error) {
	data, err := c.File(ctx, pid, remote.JournalPublicKeyFile, branch)
	if gitlab.IsNotFound(err) {
		return "", fmt.Errorf("%w (%s missing)", ErrNoJournalKey, remote.JournalPublicKeyFile)
	}
	if err != nil {
		return "", err
	}
	pub, err := remote.ParseJournalPublicKey(string(data))
	if err != nil {
		return "", fmt.Errorf("%w (%s: %v)", ErrNoJournalKey, remote.JournalPublicKeyFile, err)
	}
	vs, err := c.Variables(ctx, pid)
	if err != nil {
		return "", err
	}
	for _, v := range vs {
		if v.Key == remote.VarJournalKey && v.Scope() == remote.RunEnvironmentScope && v.Masked && v.Protected {
			if v.Description != journalKeyDescription(pub) {
				return "", fmt.Errorf("%w (%s does not match %s)", ErrNoJournalKey, remote.VarJournalKey, remote.JournalPublicKeyFile)
			}
			return pub, nil
		}
	}
	return "", fmt.Errorf("%w (%s missing)", ErrNoJournalKey, remote.VarJournalKey)
}

// journalKeyPair keeps the journal key pair of oh-runner, or creates it:
// the private key as a masked, protected variable of the run job only, the
// public key as a file of the repository (read by every member's machine
// when it sends a session). A new pair makes the sessions sent with the
// old one unreadable by their job: only when the pair is missing or broken.
func (s *Service) journalKeyPair(ctx context.Context, c *gitlab.Client, rep *Report, pid, branch string) error {
	if _, err := journalKeyState(ctx, c, pid, branch); err == nil {
		rep.add(StepJournal, StepOK, nil, remote.VarJournalKey)
		return nil
	} else if !errors.Is(err, ErrNoJournalKey) {
		rep.add(StepJournal, StepFailed, err, remote.VarJournalKey)
		return err
	}
	pub, priv, err := remote.NewJournalKeyPair()
	if err != nil {
		return err
	}
	v := gitlab.Variable{Key: remote.VarJournalKey, Value: priv, Masked: true, Protected: true, Raw: true,
		EnvironmentScope: remote.RunEnvironmentScope, Description: journalKeyDescription(pub)}
	if err := c.SetVariable(ctx, pid, v); err != nil {
		rep.add(StepJournal, StepFailed, err, remote.VarJournalKey)
		return err
	}
	if err := c.DeleteVariable(ctx, pid, v.Key, "*"); err != nil {
		rep.add(StepJournal, StepFailed, err, remote.VarJournalKey)
		return err
	}
	_, ferr := c.File(ctx, pid, remote.JournalPublicKeyFile, branch)
	if err := c.CommitFile(ctx, pid, branch, remote.JournalPublicKeyFile, []byte(pub+"\n"),
		"oh: public key of the journal keys of remote sessions", gitlab.IsNotFound(ferr)); err != nil {
		rep.add(StepJournal, StepFailed, err, remote.JournalPublicKeyFile)
		return err
	}
	rep.add(StepJournal, StepCreated, nil, remote.VarJournalKey, remote.JournalPublicKeyFile)
	return nil
}

func (s *Service) access(ctx context.Context, c *gitlab.Client, rep *Report) (*gitlab.User, error) {
	u, err := c.CurrentUser(ctx)
	if err != nil {
		rep.add(StepAccess, StepFailed, err, c.BaseURL())
		return nil, err
	}
	rep.add(StepAccess, StepOK, nil, u.Username, c.BaseURL())
	return u, nil
}

func (s *Service) features(rep *Report, p *gitlab.Project) bool {
	var missing []string
	if !p.PackagesOn() {
		missing = append(missing, "packages")
	}
	if !p.RegistryEnabled() {
		missing = append(missing, "container_registry")
	}
	if len(missing) > 0 {
		rep.add(StepFeatures, StepFailed, errors.New("disabled: "+strings.Join(missing, ", ")), strings.Join(missing, ", "))
		return false
	}
	rep.add(StepFeatures, StepOK, nil)
	return true
}

func (s *Service) protected(ctx context.Context, c *gitlab.Client, rep *Report, pid, branch string) {
	ok, err := c.BranchProtected(ctx, pid, branch)
	switch {
	case err != nil:
		rep.add(StepProtected, StepWarn, err, branch)
	case !ok:
		rep.add(StepProtected, StepFailed, errors.New("not protected: protected CI variables are not exposed"), branch)
	default:
		rep.add(StepProtected, StepOK, nil, branch)
	}
}

func ciOptions(t config.RemoteTarget) ciconfig.Options {
	return ciconfig.Options{Tag: t.Tag, Builder: t.Builder, Arch: t.Arch, Timeout: t.Timeout}
}

func (s *Service) pipeline(ctx context.Context, c *gitlab.Client, rep *Report, pid, branch string, t config.RemoteTarget, force bool) error {
	want, err := ciconfig.Generate(ciOptions(t))
	if err != nil {
		return err
	}
	cur, err := c.File(ctx, pid, CIFile, branch)
	switch {
	case gitlab.IsNotFound(err):
		if err := c.CommitFile(ctx, pid, branch, CIFile, want, "oh: pipeline of remote sessions", true); err != nil {
			rep.add(StepPipeline, StepFailed, err, CIFile)
			return err
		}
		rep.add(StepPipeline, StepCreated, nil, CIFile)
	case err != nil:
		rep.add(StepPipeline, StepFailed, err, CIFile)
		return err
	case bytes.Equal(cur, want):
		rep.add(StepPipeline, StepOK, nil, CIFile)
	case !bytes.HasPrefix(cur, []byte(ciconfig.Marker)) && !force:
		rep.add(StepPipeline, StepFailed, ErrForeignPipeline, CIFile)
		return ErrForeignPipeline
	default:
		if err := c.CommitFile(ctx, pid, branch, CIFile, want, fmt.Sprintf("oh: pipeline of remote sessions (schema %d)", remote.PipelineSchema), false); err != nil {
			rep.add(StepPipeline, StepFailed, err, CIFile)
			return err
		}
		rep.add(StepPipeline, StepUpdated, nil, CIFile)
	}
	return nil
}

func (s *Service) trigger(ctx context.Context, c *gitlab.Client, rep *Report, pid string, t config.RemoteTarget) error {
	key := t.TriggerKeyOrDefault()
	cur, _ := s.Secrets.Get(ctx, key)
	if cur != "" {
		ts, err := c.Triggers(ctx, pid)
		if err == nil && slices.ContainsFunc(ts, func(tr gitlab.Trigger) bool { return tr.Token == cur }) {
			rep.add(StepTrigger, StepOK, nil, key)
			return nil
		}
		// Unknown to GitLab (revoked) or not listable: replaced below.
	}
	tr, err := c.CreateTrigger(ctx, pid, "oh remote sessions")
	if err != nil {
		rep.add(StepTrigger, StepFailed, err, key)
		return err
	}
	if err := s.Secrets.Set(ctx, key, tr.Token); err != nil {
		rep.add(StepTrigger, StepFailed, err, key)
		return err
	}
	rep.add(StepTrigger, StepCreated, nil, key)
	return nil
}

func (s *Service) variables(ctx context.Context, c *gitlab.Client, rep *Report, pid string, req SetupRequest) error {
	set := func(v gitlab.Variable) error {
		if err := c.SetVariable(ctx, pid, v); err != nil {
			rep.add(StepVariable, StepFailed, err, v.Key)
			return err
		}
		rep.add(StepVariable, StepUpdated, nil, v.Key)
		return nil
	}
	// Secrets are scoped to the run job (S-02); a copy visible to every job
	// (left by an older oh) is removed.
	secret := func(key, value, scope string) gitlab.Variable {
		return gitlab.Variable{Key: key, Value: value, Masked: true, Protected: true, Raw: true, EnvironmentScope: scope}
	}
	setSecret := func(v gitlab.Variable) error {
		if err := set(v); err != nil {
			return err
		}
		if err := c.DeleteVariable(ctx, pid, v.Key, "*"); err != nil {
			rep.add(StepVariable, StepFailed, err, v.Key)
			return err
		}
		return nil
	}
	if req.LLM != nil {
		if err := set(gitlab.Variable{Key: remote.VarLLMProvider, Value: req.LLM.Provider, Protected: true, Raw: true}); err != nil {
			return err
		}
		if req.LLM.Region != "" {
			if err := set(gitlab.Variable{Key: remote.VarLLMRegion, Value: req.LLM.Region, Protected: true, Raw: true}); err != nil {
				return err
			}
		}
		if err := setSecret(secret(remote.VarLLMKey, req.LLM.Key, remote.RunEnvironmentScope)); err != nil {
			return err
		}
	}
	for _, pt := range req.Projects {
		p, err := c.Project(ctx, pt.Path)
		if err != nil {
			rep.add(StepVariable, StepFailed, err, pt.Path)
			return err
		}
		if err := setSecret(secret(remote.ProjectTokenVar(p.ID), pt.Token, remote.RunEnvironment(p.ID))); err != nil {
			return err
		}
	}
	if req.TeamStateToken != "" {
		if err := setSecret(secret(remote.VarTeamStateToken, req.TeamStateToken, remote.RunEnvironmentScope)); err != nil {
			return err
		}
	}
	s.reportVariables(ctx, c, rep, pid)
	return nil
}

// reportVariables lists the required variables that are missing.
func (s *Service) reportVariables(ctx context.Context, c *gitlab.Client, rep *Report, pid string) {
	vs, err := c.Variables(ctx, pid)
	if err != nil {
		rep.add(StepVariable, StepWarn, err, "*")
		return
	}
	have := map[string]gitlab.Variable{}
	projects := 0
	for _, v := range vs {
		if !secretScopeOK(v) {
			// Visible to the image build jobs (S-02): set it again.
			rep.add(StepVariable, StepFailed, fmt.Errorf("visible to every job (environment scope %s)", v.Scope()), v.Key)
			continue
		}
		have[v.Key] = v
		if _, ok := remote.ProjectTokenID(v.Key); ok {
			projects++
		}
	}
	for _, k := range []string{remote.VarLLMProvider, remote.VarLLMKey} {
		if _, ok := have[k]; !ok {
			rep.add(StepVariable, StepFailed, errors.New("missing"), k)
		}
	}
	if v, ok := have[remote.VarLLMKey]; ok && !v.Masked {
		rep.add(StepVariable, StepFailed, errors.New("not masked"), remote.VarLLMKey)
	}
	if _, ok := have[remote.VarTeamStateToken]; !ok {
		rep.add(StepVariable, StepWarn, errors.New("missing: claims not updated by the runner"), remote.VarTeamStateToken)
	}
	if projects == 0 {
		rep.add(StepVariable, StepWarn, errors.New("no project token"), remote.ProjectTokenVar(0))
	} else {
		rep.add(StepVariable, StepOK, nil, fmt.Sprint(projects))
	}
}

func (s *Service) runners(ctx context.Context, c *gitlab.Client, rep *Report, pid string, t config.RemoteTarget) {
	tag := t.Tag
	if tag == "" {
		tag = ciconfig.DefaultTag
	}
	rs, err := c.OnlineRunners(ctx, pid, tag)
	switch {
	case err != nil:
		rep.add(StepRunners, StepWarn, err, tag)
	case len(rs) == 0:
		rep.add(StepRunners, StepWarn, errors.New("no online runner"), tag)
	default:
		rep.add(StepRunners, StepOK, nil, tag, fmt.Sprint(len(rs)))
	}
}

func archOf(t config.RemoteTarget) string {
	if t.Arch == "" {
		return ciconfig.DefaultArch
	}
	return t.Arch
}

// BinaryKey is the key of Target.Binaries.
func BinaryKey(version, arch string) string { return version + "/" + arch }

var releaseRe = regexp.MustCompile(`^v?\d+\.\d+\.\d+$`)

// IsRelease reports whether version is a published release (downloaded by
// the job) rather than a development build (uploaded by setup).
func IsRelease(version string) bool { return releaseRe.MatchString(version) }

// binary reports how the job gets the oh binary of this version.
func (s *Service) binary(rep *Report, t config.RemoteTarget) {
	switch {
	case IsRelease(s.OhVersion):
		rep.add(StepBinary, StepOK, nil, s.OhVersion, "release")
	case t.Binaries[BinaryKey(s.OhVersion, archOf(t))] != "":
		rep.add(StepBinary, StepOK, nil, s.OhVersion, t.Binaries[BinaryKey(s.OhVersion, archOf(t))][:12])
	default:
		rep.add(StepBinary, StepFailed, errors.New("development build not uploaded: oh remote setup --oh-binary"), s.OhVersion)
	}
}

// elfMagic starts every Linux executable.
var elfMagic = []byte{0x7f, 'E', 'L', 'F'}

// uploadBinary uploads a Linux oh binary as oh-cli/<sha256>/oh-linux-<arch>
// and returns the package version.
func (s *Service) uploadBinary(ctx context.Context, c *gitlab.Client, pid, path, arch string) (string, error) {
	f, err := os.Open(path)
	if err != nil {
		return "", err
	}
	defer f.Close()
	st, err := f.Stat()
	if err != nil {
		return "", err
	}
	head := make([]byte, 4)
	if _, err := io.ReadFull(f, head); err != nil || !bytes.Equal(head, elfMagic) {
		return "", fmt.Errorf("%s is not a Linux executable (build it with make build-linux)", path)
	}
	h := sha256.New()
	if _, err := f.Seek(0, io.SeekStart); err != nil {
		return "", err
	}
	if _, err := io.Copy(h, f); err != nil {
		return "", err
	}
	version := hex.EncodeToString(h.Sum(nil))
	exists, err := c.GenericPackageExists(ctx, pid, remote.PackageCLI, version, remote.CLIFile(arch))
	if err != nil {
		return "", err
	}
	if exists {
		return version, nil
	}
	if _, err := f.Seek(0, io.SeekStart); err != nil {
		return "", err
	}
	if _, err := c.UploadGenericPackage(ctx, pid, remote.PackageCLI, version, remote.CLIFile(arch), f, st.Size()); err != nil {
		return "", err
	}
	return version, nil
}

// secretScopeOK reports whether a variable of oh-runner is visible only
// where it must be: the secrets to the run job (a project token to the run
// job of its project), the other variables anywhere.
func secretScopeOK(v gitlab.Variable) bool {
	if id, ok := remote.ProjectTokenID(v.Key); ok {
		return v.Scope() == remote.RunEnvironment(id)
	}
	switch v.Key {
	case remote.VarLLMKey, remote.VarTeamStateToken, remote.VarJournalKey:
		return v.Scope() == remote.RunEnvironmentScope
	}
	return true
}
