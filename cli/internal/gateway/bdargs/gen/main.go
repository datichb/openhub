//go:build ignore

// Command gen writes the bd command and flag table of the bdargs package
// from the help of the installed bd (go run ./gen/main.go > spec_bd.go, from
// internal/gateway/bdargs). Every command is walked recursively.
package main

import (
	"bufio"
	"context"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"regexp"
	"sort"
	"strings"
	"time"
)

var (
	cmdLine  = regexp.MustCompile(`^  ([a-z][a-z0-9-]*)\s{2,}\S`)
	flagLine = regexp.MustCompile(`^\s+(?:-([A-Za-z0-9]), )?--([A-Za-z0-9][A-Za-z0-9_-]*)(?: ([A-Za-z0-9]+)(\[="[^"]*"\])?)?(?:\s{2,}|$)`)
	header   = regexp.MustCompile(`^([A-Z][A-Za-z &]*):\s*$`)
)

type help struct {
	bogus   bool
	subs    []string
	aliases []string
	flags   []string
	global  []string
}

func run(path []string) help {
	if len(path) > 6 {
		return help{}
	}
	ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, "bd", append(append([]string{}, path...), "--help")...)
	cmd.Dir = os.TempDir()
	out, _ := cmd.CombinedOutput()
	var h help
	usage := "bd " + strings.Join(path, " ")
	if len(path) > 0 && !strings.Contains(string(out), "\n  "+usage+" ") && !strings.Contains(string(out), "\n  "+usage+"\n") {
		return help{bogus: true}
	}
	section := ""
	sc := bufio.NewScanner(strings.NewReader(string(out)))
	for sc.Scan() {
		line := sc.Text()
		if m := header.FindStringSubmatch(line); m != nil {
			section = m[1]
			continue
		}
		switch section {
		case "Usage", "Examples", "Additional help topics", "":
		case "Aliases":
			for _, a := range strings.Split(strings.TrimSpace(line), ",") {
				if a = strings.TrimSpace(a); a != "" && (len(path) == 0 || a != path[len(path)-1]) {
					h.aliases = append(h.aliases, a)
				}
			}
		case "Flags", "Global Flags":
			m := flagLine.FindStringSubmatch(line)
			if m == nil {
				continue
			}
			tok := m[2]
			if m[1] != "" {
				tok += "/" + m[1]
			}
			switch {
			case m[3] == "" || m[3] == "count":
			case m[4] != "":
				tok += "?"
			default:
				tok += "="
			}
			if section == "Flags" {
				h.flags = append(h.flags, tok)
			} else {
				h.global = append(h.global, tok)
			}
		default:
			if m := cmdLine.FindStringSubmatch(line); m != nil && m[1] != "help" && m[1] != "completion" {
				h.subs = append(h.subs, m[1])
			}
		}
	}
	return h
}

func main() {
	version, _ := exec.Command("bd", "version").Output()
	root := run(nil)
	globals := map[string]bool{}
	for _, f := range root.flags {
		globals[f] = true
	}
	specs := map[string]string{}
	aliases := map[string]string{}
	var walk func(path []string, h help)
	walk = func(path []string, h help) {
		if h.bogus {
			return
		}
		if len(path) > 0 {
			var own []string
			for _, f := range append(append([]string{}, h.flags...), h.global...) {
				if !globals[f] {
					own = append(own, f)
				}
			}
			sort.Strings(own)
			key := strings.Join(path, " ")
			specs[key] = strings.Join(dedup(own), " ")
			if len(h.aliases) > 0 {
				aliases[key] = strings.Join(h.aliases, " ")
			}
		}
		for _, s := range h.subs {
			p := append(append([]string{}, path...), s)
			walk(p, run(p))
		}
	}
	walk(nil, root)
	keys := make([]string, 0, len(specs))
	for k := range specs {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by go run ./gen/main.go; DO NOT EDIT.\n// Source: %s\n\npackage bdargs\n\n", strings.TrimSpace(string(version)))
	fmt.Fprintf(&b, "// GeneratedFor is the bd version the table was generated from.\nconst GeneratedFor = %q\n\n", strings.TrimSpace(string(version)))
	globalList := append([]string{}, root.flags...)
	sort.Strings(globalList)
	fmt.Fprintf(&b, "// globalSpec are the flags of every command (persistent flags of bd).\nconst globalSpec = %q\n\n", strings.Join(globalList, " "))
	b.WriteString("// commandSpecs are the commands (space-separated path) and their own flags:\n// name[/short] then = (value), ? (optional value) or nothing (boolean).\nvar commandSpecs = map[string]string{\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "\t%q: %q,\n", k, specs[k])
	}
	b.WriteString("}\n\n// commandAliases are the other names of a command.\nvar commandAliases = map[string]string{\n")
	akeys := make([]string, 0, len(aliases))
	for k := range aliases {
		akeys = append(akeys, k)
	}
	sort.Strings(akeys)
	for _, k := range akeys {
		fmt.Fprintf(&b, "\t%q: %q,\n", k, aliases[k])
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	os.Stdout.Write(src)
}

func dedup(in []string) []string {
	var out []string
	for i, s := range in {
		if i == 0 || s != in[i-1] {
			out = append(out, s)
		}
	}
	return out
}
